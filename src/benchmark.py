"""Step 5: aggregate results/*.json into results/benchmark.md and figures.

Outputs
    results/benchmark.md                  main table + per-class F1 + generalisation gap
    results/figures/macro_f1.png          macro-F1 per model on both test splits
    results/figures/confusion_<best>.png  confusion matrix of the best model (random test split)
"""
import json

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

from common import RESULTS

ORDER = ["majority_class", "naive_bayes", "logistic_regression", "linear_svm", "textcnn", "bilstm",
         "distilbert", "modernbert", "laya_zero_shot"]
PRETTY = {"majority_class": "Majority class", "naive_bayes": "Naive Bayes", "logistic_regression": "Logistic Regression",
          "linear_svm": "Linear SVM", "textcnn": "TextCNN", "bilstm": "BiLSTM", "distilbert": "DistilBERT",
          "modernbert": "ModernBERT-base", "laya_zero_shot": "Laya (zero-shot)"}


def load():
    rs = {p.stem: json.loads(p.read_text()) for p in RESULTS.glob("*.json")}
    return [rs[k] for k in ORDER if k in rs]


def fmt(x):
    return f"{x:.3f}"


def table(rs):
    lines = ["| Model | Type | Test macro-F1 | Test accuracy | Unseen-repos macro-F1 | Unseen-repos accuracy | Train time (s) |",
             "|---|---|---|---|---|---|---|"]
    best = max(r["scores"]["test"]["macro_f1"] for r in rs)
    for r in rs:
        t, u = r["scores"]["test"], r["scores"]["test_unseen_repos"]
        f1 = fmt(t["macro_f1"])
        if "seed_stats" in r:
            f1 += f" (±{r['seed_stats']['test']['macro_f1_std']:.3f})"
        if t["macro_f1"] == best:
            f1 = f"**{f1}**"
        lines.append(f"| {PRETTY[r['model']]} | {r['family']} | {f1} | {fmt(t['accuracy'])} | "
                     f"{fmt(u['macro_f1'])} | {fmt(u['accuracy'])} | {r['train_seconds']} |")
    return "\n".join(lines)


def per_class(rs):
    labels = rs[0]["labels"]
    lines = ["| Model | " + " | ".join(labels) + " |", "|---|" + "---|" * len(labels)]
    for r in rs:
        pc = r["scores"]["test"]["per_class"]
        lines.append(f"| {PRETTY[r['model']]} | " + " | ".join(fmt(pc[l]["f1-score"]) for l in labels) + " |")
    return "\n".join(lines)


def plot_f1(rs, path):
    names = [PRETTY[r["model"]] for r in rs]
    x = np.arange(len(rs))
    fig, ax = plt.subplots(figsize=(10, 4.2))
    ax.bar(x - 0.2, [r["scores"]["test"]["macro_f1"] for r in rs], 0.4, label="random test split", color="#2f6fb0")
    ax.bar(x + 0.2, [r["scores"]["test_unseen_repos"]["macro_f1"] for r in rs], 0.4, label="unseen repositories",
           color="#e08a2c")
    ax.set_xticks(x, names, rotation=25, ha="right")
    ax.set_ylabel("macro-F1")
    ax.set_ylim(0, 1)
    ax.grid(axis="y", alpha=0.3)
    ax.legend(frameon=False)
    ax.set_title("Commit type classification: macro-F1 (10 classes)")
    fig.tight_layout()
    fig.savefig(path, dpi=160)
    plt.close(fig)


def plot_cm(r, path):
    labels = r["labels"]
    cm = np.array(r["scores"]["test"]["confusion_matrix"], dtype=float)
    cmn = cm / cm.sum(1, keepdims=True)
    fig, ax = plt.subplots(figsize=(6.4, 5.6))
    im = ax.imshow(cmn, cmap="Blues", vmin=0, vmax=1)
    ax.set_xticks(range(len(labels)), labels, rotation=45, ha="right")
    ax.set_yticks(range(len(labels)), labels)
    for i in range(len(labels)):
        for j in range(len(labels)):
            ax.text(j, i, f"{cmn[i, j]:.2f}", ha="center", va="center", fontsize=7,
                    color="white" if cmn[i, j] > 0.5 else "black")
    ax.set_xlabel("predicted")
    ax.set_ylabel("true")
    ax.set_title(f"{PRETTY[r['model']]}: row-normalised confusion matrix")
    fig.colorbar(im, ax=ax, fraction=0.046)
    fig.tight_layout()
    fig.savefig(path, dpi=160)
    plt.close(fig)


def main():
    rs = load()
    figs = RESULTS / "figures"
    figs.mkdir(exist_ok=True)
    best = max(rs, key=lambda r: r["scores"]["test"]["macro_f1"])
    plot_f1(rs, figs / "macro_f1.png")
    plot_cm(best, figs / f"confusion_{best['model']}.png")
    notes = []
    for r in rs:
        if r["model"] == "laya_zero_shot":
            notes.append(f"- Laya is evaluated on stratified samples of {r['params']['eval_sample_size']} commits "
                         "(CPU inference cost); it uses no training data.")
        if "train_size" in r["params"] and r["params"]["train_size"] < 85000:
            notes.append(f"- {PRETTY[r['model']]} was fine-tuned on a stratified subsample of "
                         f"{r['params']['train_size']} training commits (CPU budget).")
        if "seed_stats" in r:
            notes.append(f"- {PRETTY[r['model']]}: median of seeds {r['params']['seeds']}; ± is the std over seeds.")
    md = ["# Benchmark", "",
          "Generated by `src/benchmark.py` from `results/*.json`. Primary metric: **macro-F1** "
          "(see README, *Why macro-F1*).", "",
          "## Main results", "", table(rs), "", *notes, "",
          "## Per-class F1 (random test split)", "", per_class(rs), "",
          "## Figures", "", "![macro-F1](figures/macro_f1.png)", "",
          f"![confusion matrix](figures/confusion_{best['model']}.png)", ""]
    (RESULTS / "benchmark.md").write_text("\n".join(md))
    print("\n".join(md[:8 + len(rs)]))


if __name__ == "__main__":
    main()
